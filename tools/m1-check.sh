#!/bin/sh
# M1 acceptance check — see spec.md §10.
#
# Starts rossh on a spare port and verifies the two M1 criteria:
#   1. the algorithm offer is the modern suite of spec.md §4.1, with nothing
#      legacy in it,
#   2. a stock OpenSSH client gets all the way to authentication with no -o
#      algorithm flags, and is refused there (serving sessions is M2).
#
#   tools/m1-check.sh [port]
#
# The client key below is generated here rather than taken from the user's
# ~/.ssh: the point is that the client reaches publickey authentication and is
# turned away, which cannot be observed on a machine that has no identity to
# offer at all (a CI runner, for one).

set -u

port=${1:-2222}
root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
log="$work/server.log"
server=""
fail=0

cleanup() {
    if [ -n "$server" ]; then
        kill "$server" 2>/dev/null
        wait "$server" 2>/dev/null
    fi
    rm -rf "$work"
}
trap cleanup EXIT INT TERM

if [ ! -x "$root/rossh" ]; then
    echo "m1-check: no ./rossh — run make first" >&2
    exit 2
fi

# A throwaway ed25519 host key, generated by rossh itself — the target has
# neither openssl nor ssh-keygen, so rossh owns this. It writes PKCS#8 DER that
# carries the public half, which wolfSSH needs. See docs/build.md.
# Never committed: see .gitignore.
if [ ! -f "$root/rossh_hostkey.der" ]; then
    echo "-- generating $root/rossh_hostkey.der"
    "$root/rossh" --genkey "$root/rossh_hostkey.der" || exit 2
fi

"$root/rossh" "$port" "$root/rossh_hostkey.der" > "$log" 2>&1 &
server=$!
sleep 1

echo "=== algorithm offer (tools/probe/kexinit.py, unauthenticated) ==="
offer=$(python3 "$root/tools/probe/kexinit.py" 127.0.0.1 "$port" --json) || {
    echo "FAIL: the probe could not read the offer"
    fail=1
}
printf '%s\n' "$offer"

expect() {
    if printf '%s' "$offer" | grep -q "$1"; then
        echo "  ok: offered $1"
    else
        echo "  FAIL: not offered: $1"
        fail=1
    fi
}
reject() {
    if printf '%s' "$offer" | grep -q "$2"; then
        echo "  FAIL: legacy still offered: $2"
        fail=1
    else
        echo "  ok: no $1"
    fi
}

echo "=== expected to be offered ==="
expect 'curve25519-sha256'
expect 'ssh-ed25519'
expect 'aes256-gcm@openssh.com'
reject 'diffie-hellman-group1' 'diffie-hellman-group1-sha1'
reject 'ssh-rsa'               'ssh-rsa'
reject 'hmac-sha1'             'hmac-sha1'
reject 'CBC'                   'aes256-cbc'

echo "=== a stock client, with no -o algorithm flags ==="
ssh-keygen -q -t ed25519 -N "" -f "$work/id" || exit 2

# IdentitiesOnly, so only the key above is offered and the result does not
# depend on what the machine running this happens to have in ~/.ssh.
out=$(ssh -vvv -p "$port" \
        -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
        -o BatchMode=yes -o ConnectTimeout=5 -o NumberOfPasswordPrompts=0 \
        -o IdentitiesOnly=yes -i "$work/id" \
        testuser@127.0.0.1 true 2>&1)

printf '%s\n' "$out" | grep -E "kex: (algorithm|host key algorithm|server->client cipher|server->client mac)"

# Both halves of the criterion: the server saw a publickey attempt, so the
# client really did reach authentication, and the client was refused there.
if grep -q 'publickey offered' "$log"; then
    echo "  ok: the server reached publickey authentication"
else
    echo "  FAIL: the server never logged a publickey attempt"
    fail=1
fi

case "$out" in
    *"Permission denied"*)
        echo "  ok: refused as intended" ;;
    *)
        echo "  FAIL: expected an authentication refusal"
        echo "--- what the client said ---"
        printf '%s\n' "$out" | grep -v '^debug[23]:'
        fail=1 ;;
esac

# The negotiated cipher is the client's choice, not ours: it picks the first
# entry of its own preference list that we offer. Testing only the default
# negotiation therefore tests one cipher — whichever the local OpenSSH happens
# to rank highest — and says nothing about the rest of the offer. An offer the
# backend cannot honour is invisible until a client with a different order
# shows up. So every advertised cipher gets its own handshake, with the list
# read back out of the server's own log so this stays in step with
# algo_cipher in src/main.c.
echo "=== every advertised cipher must complete a handshake ==="
ciphers=$(sed -n 's/.*\[INFO\]   cipher   //p' "$log" | head -1 | tr ',' ' ')
if [ -z "$ciphers" ]; then
    echo "  FAIL: could not read the offered cipher list from the log"
    fail=1
fi
for c in $ciphers; do
    cout=$(ssh -p "$port" -c "$c" \
             -o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null \
             -o BatchMode=yes -o ConnectTimeout=5 -o NumberOfPasswordPrompts=0 \
             -o IdentitiesOnly=yes -i "$work/id" \
             testuser@127.0.0.1 true 2>&1)
    case "$cout" in
        *"Permission denied"*)
            echo "  ok: $c reached authentication" ;;
        *)
            echo "  FAIL: $c did not get as far as authentication"
            printf '%s\n' "$cout" | grep -v '^debug' | sed 's/^/      /'
            fail=1 ;;
    esac
done

echo "=== server log ==="
cat "$log"

if [ "$fail" -eq 0 ]; then
    echo "M1: PASS"
else
    echo "M1: FAIL"
fi
exit "$fail"
